export function spellDescriptors(wrapper: SpellDescriptorWrapper): string[] {
  const bits = BigInt.asUintN(64, BigInt(wrapper.m_IntValue));
  return SPELL_DESCRIPTORS.filter((_, i) => ((bits >> BigInt(i)) & 1n) === 1n);
}
